def certificate_expiry(path: Path) -> tuple[str, int | None]:
    """Return (notAfter, days_left). days_left is None when openssl cannot tell us."""
    if not command_exists("openssl") or not path.is_file():
        return "", None
    result = run(["openssl", "x509", "-in", str(path), "-noout", "-enddate"], capture=True, check=False)
    match = re.search(r"notAfter=(.+)", (result.stdout or "").strip())
    if not match:
        return "", None
    not_after = match.group(1).strip()
    for fmt in ("%b %d %H:%M:%S %Y %Z", "%b %d %H:%M:%S %Y"):
        try:
            expiry = time.mktime(time.strptime(not_after.replace(" GMT", ""), fmt.replace(" %Z", "")))
        except ValueError:
            continue
        return not_after, int((expiry - time.time()) // 86400)
    return not_after, None


def doctor_tls(values: dict[str, str]) -> int:
    failures = 0
    tls_disable = values.get("tls_disable", "")
    doctor_info(f"tls_disable  = {unset_label(tls_disable)}")
    if tls_disable != "false":
        doctor_check("WARN", "Listener TLS is disabled; tokens travel in clear text")
        return failures
    for key in ("tls_cert_file", "tls_key_file"):
        value = values.get(key, "")
        if not value:
            doctor_check("FAIL", f"TLS is enabled but {key} is not set")
            failures += 1
            continue
        if Path(value).is_file():
            doctor_check("OK", f"{key} exists: {value}")
        else:
            doctor_check("FAIL", f"{key} missing: {value}; vault.service will not start")
            failures += 1
    cert_file = values.get("tls_cert_file", "")
    if cert_file and Path(cert_file).is_file():
        not_after, days_left = certificate_expiry(Path(cert_file))
        if days_left is None:
            doctor_info(f"certificate expiry = {unset_label(not_after)}")
        elif days_left < 0:
            doctor_check("FAIL", f"Certificate expired {abs(days_left)} days ago: {not_after}")
            failures += 1
        elif days_left <= CERT_EXPIRY_WARN_DAYS:
            doctor_check("WARN", f"Certificate expires in {days_left} days: {not_after}")
        else:
            doctor_check("OK", f"Certificate valid for {days_left} more days")
    return failures


def doctor_init_output() -> int:
    """The init file holds every unseal key and the root token, so its mode matters."""
    if not INIT_DIR.exists():
        doctor_info(f"Init output: {INIT_DIR} does not exist")
        return 0
    failures = 0
    files = sorted(path for path in INIT_DIR.glob("*.json") if path.is_file())
    if not files:
        doctor_info(f"Init output: no JSON files under {INIT_DIR}")
        return 0
    for path in files:
        mode = path.stat().st_mode & 0o777
        owner = path.stat().st_uid
        if mode == 0o600 and owner == 0:
            doctor_check("OK", f"{path.name}: mode 0600, owned by root")
        else:
            doctor_check("FAIL", f"{path.name}: mode {mode:04o}, uid {owner}; unseal keys must be 0600 root-owned")
            failures += 1
    return failures


def doctor_node_runtime() -> int:
    failures = 0
    recorded = read_installed_vault_version()
    doctor_info(f"recorded version = {recorded}")
    doctor_info(f"tool revision    = {read_installed_tool_revision()}")
    actual = installed_binary_version()
    if actual:
        doctor_info(f"binary version   = {actual}")
        if recorded not in {"unknown", actual}:
            doctor_check("WARN", f"Binary version {actual} differs from recorded {recorded}; "
                                 f"run {VAULT_MANAGER_CMD} upgrade to install a known release")
    for path, label, required in ((DATA_DIR, "Raft data directory", True), (TOOL_DIR, "Tool copy", False)):
        if path.is_dir():
            doctor_check("OK", f"{label} exists: {path}")
        elif required:
            doctor_check("FAIL", f"{label} missing: {path}")
            failures += 1
        else:
            doctor_check("WARN", f"{label} missing: {path}; this node was not installed by vault-manager")
    return failures


def doctor_seal_state(client: VaultClient) -> int:
    status = client.status_json()
    if not status:
        doctor_check("WARN", "Cannot read vault status; check the address, TLS and whether the binary is installed")
        return 0
    failures = 0
    initialized = status.get("initialized")
    sealed = status.get("sealed")
    if initialized is True:
        doctor_check("OK", "Vault is initialized")
    else:
        doctor_check("FAIL", f"Vault is not initialized; run {VAULT_MANAGER_CMD} init")
        failures += 1
    if sealed is False:
        doctor_check("OK", "Vault is unsealed")
    elif sealed is True:
        doctor_check("FAIL", f"Vault is sealed; run {VAULT_MANAGER_CMD} unseal --keys-file {DEFAULT_INIT_FILE}")
        failures += 1
    if status.get("t") or status.get("n"):
        doctor_info(f"seal threshold   = {status.get('t', '?')} of {status.get('n', '?')}")
    if status.get("ha_enabled") is not None:
        doctor_info(f"ha_enabled       = {str(status.get('ha_enabled')).lower()}")
    if status.get("version"):
        doctor_info(f"server version   = {status.get('version')}")
    return failures


def cmd_doctor(args: argparse.Namespace) -> int:
    client = VaultClient(args)
    values = config_values()
    failures = 0
    doctor_check("OK" if sys.platform.startswith("linux") else "FAIL", f"platform: {sys.platform}")
    if not sys.platform.startswith("linux"):
        failures += 1
    if command_exists("systemctl"):
        doctor_check("OK", f"systemctl found: {shutil.which('systemctl')}")
        if run(["systemctl", "is-active", "--quiet", "vault"], check=False).returncode == 0:
            doctor_check("OK", "vault.service is active")
        else:
            doctor_check("FAIL", "vault.service is not active")
            failures += 1
    else:
        doctor_check("FAIL", "systemctl not found")
        failures += 1
    if BIN_PATH.is_file():
        doctor_check("OK", f"Vault binary found: {BIN_PATH}")
    else:
        doctor_check("FAIL", f"Vault binary missing: {BIN_PATH}")
        failures += 1
    if CONFIG_FILE.is_file():
        if is_managed_file(CONFIG_FILE):
            doctor_check("OK", f"Vault config managed: {CONFIG_FILE}")
        else:
            doctor_check("FAIL", f"Vault config exists but is not managed: {CONFIG_FILE}")
            failures += 1
    else:
        doctor_check("FAIL", f"Vault config missing: {CONFIG_FILE}")
        failures += 1

    print("\nNode runtime:")
    failures += doctor_node_runtime()

    print("\nConfiguration:")
    if not values:
        doctor_check("FAIL", f"Config not readable: {CONFIG_FILE}")
        failures += 1
    else:
        doctor_info(f"api_addr     = {unset_label(values['api_addr'])}")
        doctor_info(f"cluster_addr = {unset_label(values['cluster_addr'])}")
        doctor_info(f"listener     = {unset_label(values['listen_address'])} "
                    f"(cluster {unset_label(values['cluster_address'])})")
        doctor_info(f"storage      = raft at {unset_label(values['storage_path'])}, node_id {unset_label(values['node_id'])}")
        failures += doctor_tls(values)
    doctor_info(f"client env   = VAULT_ADDR {unset_label(client_env_value('VAULT_ADDR'))}, "
                f"VAULT_CACERT {unset_label(client_env_value('VAULT_CACERT'))}")

    print("\nInit output:")
    failures += doctor_init_output()

    print("\nVault state:")
    url = client.health_url()
    code = http_status(url, cafile=client.ca_cert)
    if code in {200, 429, 472, 473}:
        doctor_check("OK", f"Vault health endpoint reachable: {url} ({code})")
    elif code in SEAL_HINTS:
        reason, fix = SEAL_HINTS[code]
        doctor_check("FAIL", f"{reason} ({code} from {url})")
        doctor_check("INFO", f"Fix: {fix}")
        failures += 1
    else:
        doctor_check("FAIL", f"Vault health endpoint not reachable: {url} ({code})")
        failures += 1
    failures += doctor_seal_state(client)
    if failures == 0:
        print("\nAll checks passed.")
    return 0 if failures == 0 else 1


