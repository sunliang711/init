def running_from_installed_copy(script_dir: Path) -> bool:
    """True when the running script is the copy that install placed under TOOL_DIR.

    Updating from there would copy the directory onto itself and change nothing.
    """
    try:
        resolved = Path(script_dir).resolve()
        tool_dir = TOOL_DIR.resolve()
    except OSError:
        return False
    return resolved == tool_dir or tool_dir in resolved.parents


def require_tool_source(script_dir: Path) -> None:
    missing: list[str] = []
    if not (script_dir / "vault-manager").is_file():
        missing.append(str(script_dir / "vault-manager"))
    if not (script_dir / "vault_tools").is_dir():
        missing.append(str(script_dir / "vault_tools"))
    if missing:
        raise CLIError(f"Tool source is incomplete: {', '.join(missing)}")


def install_tool_snapshot(version: str, script_dir: Path) -> None:
    revision, dirty = source_tool_revision(script_dir)
    log_info(f"Installing Vault init tools snapshot: {TOOL_DIR} (source revision {revision}{'-dirty' if dirty else ''})")
    run_root(["install", "-d", "-m", "0755", "-o", "root", "-g", "root", str(BIN_DIR)])
    run_root(["install", "-d", "-m", "0755", "-o", "root", "-g", "root", str(TOOL_DIR)])
    safe_remove_path(TOOL_DIR / "manager.sh")
    run_root(["install", "-m", "0755", "-o", "root", "-g", "root", str(script_dir / "vault-manager"), str(TOOL_DIR / "vault-manager")])
    safe_remove_path(TOOL_DIR / "vault_tools")
    run_root(["cp", "-R", str(script_dir / "vault_tools"), str(TOOL_DIR / "vault_tools")])
    run_root(["chown", "-R", "root:root", str(TOOL_DIR / "vault_tools")])
    install_text(
        TOOL_VERSION_FILE,
        f"tool=vault-manager\nvault_version={version}\ntool_revision={revision}\n"
        f"tool_revision_dirty={str(dirty).lower()}\n"
        f"installed_at={time.strftime('%Y-%m-%dT%H:%M:%S%z')}\nsource_dir={script_dir}\n",
        mode="0644",
    )
    write_tool_manifest()
    write_install_metadata(version, revision, dirty)
    run_root(["ln", "-sfn", str(TOOL_DIR / "vault-manager"), str(TOOL_PATH)])
    run_root(["install", "-d", "-m", "0755", "-o", "root", "-g", "root", str(TOOL_ENTRY.parent)])
    run_root(["ln", "-sfn", str(TOOL_PATH), str(TOOL_ENTRY)])
    if LEGACY_TOOL_ENTRY.is_symlink():
        safe_remove_path(LEGACY_TOOL_ENTRY)
    log_success(f"Vault manager entry installed: {TOOL_ENTRY}")


def cmd_tools_update(args: argparse.Namespace) -> int:
    require_linux()
    require_command("install")
    script_dir = current_script_dir(__file__).parent
    if running_from_installed_copy(script_dir):
        raise CLIError(
            f"Refusing to update from the installed copy at {TOOL_DIR}: it would copy onto itself "
            f"and change nothing. Run tools update from a source checkout instead"
        )
    require_tool_source(script_dir)
    version = normalize_version(args.vault_version) if args.vault_version else read_installed_vault_version()
    if version == "unknown":
        log_warn("Installed Vault version metadata not found; recording unknown")
    log_info(f"Updating Vault init tool files from: {script_dir}")
    install_tool_snapshot(version, script_dir)
    log_success("Vault init tools updated")
    return 0


def resolve_install_tls(args: argparse.Namespace) -> argparse.Namespace:
    """Turn the TLS flags into the concrete settings write_vault_config needs."""
    custom_set = bool(args.tls_cert_file or args.tls_key_file or args.tls_ca_cert_file)
    auto_options_set = bool(args.tls_dns or args.tls_ip or args.tls_common_name != "vault-server")
    if args.no_tls and (args.tls_auto or custom_set or auto_options_set):
        raise CLIError("--no-tls cannot be used with TLS options")
    if args.tls_auto and custom_set:
        raise CLIError("--tls-auto cannot be used with custom TLS certificate options")
    if auto_options_set and not args.tls_auto:
        raise CLIError("--tls-dns, --tls-ip and --tls-common-name require --tls-auto")

    mode = "auto" if args.tls_auto else ("custom" if custom_set else "disabled")
    api_addr = args.api_addr or DEFAULT_VAULT_ADDR
    cluster_addr = args.cluster_addr or DEFAULT_CLUSTER_ADDR
    if mode != "disabled":
        api_addr = args.api_addr or "https://127.0.0.1:8200"
        cluster_addr = args.cluster_addr or "https://127.0.0.1:8201"
        if not api_addr.startswith("https://"):
            raise CLIError("TLS is enabled; --api-addr must use https://")
        if not cluster_addr.startswith("https://"):
            raise CLIError("TLS is enabled; --cluster-addr must use https://")
        if mode == "custom" and not (args.tls_cert_file and args.tls_key_file):
            raise CLIError("TLS custom certificate requires both --tls-cert-file and --tls-key-file")
        for label, value in (("certificate", args.tls_cert_file), ("key", args.tls_key_file),
                             ("CA certificate", args.tls_ca_cert_file)):
            if value and not Path(value).is_file():
                raise CLIError(f"TLS {label} file not found: {value}")
    for value in args.tls_dns:
        validate_tls_value("TLS DNS name", value)
    for value in args.tls_ip:
        validate_tls_value("TLS IP address", value)
    return argparse.Namespace(
        mode=mode,
        api_addr=api_addr,
        cluster_addr=cluster_addr,
        listen_address=args.listen_address,
        cluster_address=args.cluster_address,
        tls_disable="false" if mode != "disabled" else "true",
        tls_cert_file=args.tls_cert_file,
        tls_key_file=args.tls_key_file,
        tls_ca_cert_file=args.tls_ca_cert_file,
        tls_common_name=args.tls_common_name,
        tls_dns=list(args.tls_dns),
        tls_ip=list(args.tls_ip),
    )


def cmd_install(args: argparse.Namespace) -> int:
    require_linux()
    for command in ("install", "systemctl", "useradd", "groupadd", "getent"):
        require_command(command)
    settings = resolve_install_tls(args)
    version = resolve_version(args.version)
    arch = detect_arch()
    tmpdir = create_install_tmpdir("vault-install")
    try:
        download_vault(version, arch, tmpdir)
        install_binary(tmpdir, version)
        ensure_vault_user()
        install_directories()
        if settings.mode == "auto":
            dns_names, ip_addresses = default_tls_sans(
                settings.tls_dns, settings.tls_ip, [settings.api_addr, settings.cluster_addr]
            )
            install_self_signed_tls_cert(tmpdir, settings.tls_common_name, dns_names, ip_addresses)
            settings.tls_cert_file = str(TLS_CERT_FILE)
            settings.tls_key_file = str(TLS_KEY_FILE)
            settings.tls_ca_cert_file = str(TLS_CA_CERT_FILE)
        write_vault_config(settings)
        write_client_env(settings.api_addr, settings.tls_ca_cert_file)
        write_systemd_service()
        script_dir = current_script_dir(__file__).parent
        if running_from_installed_copy(script_dir):
            log_warn(f"Running the copy installed at {TOOL_DIR}; the tool files will not change")
            log_warn("Run install from a source checkout to update vault-manager as well")
        install_tool_snapshot(version, script_dir)
        write_state_pointer()
        log_info("Enabling Vault service")
        run_root(["systemctl", "daemon-reload"])
        run_root(["systemctl", "enable", "vault"])
        run_root(["systemctl", "restart", "vault"])
        wait_for_vault_api(VaultClient(argparse.Namespace(addr=settings.api_addr, ca_cert=settings.tls_ca_cert_file)))
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    log_success("Vault installation completed")
    print_install_next_steps()
    return 0


def restart_vault_service(client: VaultClient) -> None:
    run_root(["systemctl", "restart", "vault"])
    time.sleep(2)
    if run_root(["systemctl", "is-active", "--quiet", "vault"], check=False).returncode != 0:
        if command_exists("journalctl"):
            run_root(["journalctl", "-u", "vault", "-n", "80", "--no-pager"], check=False)
        raise CLIError("Vault service failed to start")
    wait_for_vault_api(client)


def read_install_metadata_as_root() -> dict[str, Any]:
    """install.json sits in a root-only directory, so a sudoer can only read it through sudo."""
    result = run_root(["cat", str(INSTALL_METADATA_FILE)], capture=True, check=False)
    if result.returncode != 0:
        return {}
    try:
        data = json.loads(result.stdout or "")
    except json.JSONDecodeError:
        return {}
    return data if isinstance(data, dict) else {}


def record_tool_version_file(version: str) -> None:
    """doctor and status fall back to this file when install.json cannot be read."""
    key = "vault_version="
    try:
        lines = TOOL_VERSION_FILE.read_text(encoding="utf-8").splitlines()
    except OSError:
        return
    if not any(line.startswith(key) for line in lines):
        return
    install_text(
        TOOL_VERSION_FILE,
        "\n".join(f"{key}{version}" if line.startswith(key) else line for line in lines) + "\n",
        mode="0644",
    )


def record_upgrade_metadata(previous: str, version: str) -> None:
    """Move the recorded version forward without rewriting the whole install record."""
    metadata = read_install_metadata() or read_install_metadata_as_root()
    if not metadata:
        log_warn(f"Install metadata not readable: {INSTALL_METADATA_FILE}; the recorded version was not updated")
        return
    metadata["vault_version"] = version
    metadata["previous_vault_version"] = previous
    metadata["upgraded_at"] = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    run_root(["install", "-d", "-m", "0750", "-o", "root", "-g", "root", str(TOOL_STATE_DIR)])
    install_text(INSTALL_METADATA_FILE, json.dumps(metadata, indent=2, sort_keys=True) + "\n", mode="0644")
    record_tool_version_file(version)


def upgrade_plan_lines(current: str, target: str, keep: int) -> list[str]:
    lines = [
        "Vault upgrade plan:",
        f"  Current version:  {current}",
        f"  Target version:   {target}",
        f"  Download:         https://releases.hashicorp.com/vault/{target}/vault_{target}_linux_{detect_arch()}.zip",
        f"  Install release:  {versioned_binary_path(BINARY_VERSION_DIR, 'vault', target)}",
        f"  Switch symlink:   {BIN_PATH}",
        "  Restart service:  vault.service",
        f"  Keep releases:    {keep} (older ones are removed once the new one is running)",
        "  Left untouched:   config, TLS material, the raft store, the init output and the tool files",
        "",
        "  Restarting Vault seals it. Every secret stays unreachable until the node is",
        f"  unsealed again, so have the unseal keys at hand ({DEFAULT_INIT_FILE} by",
        "  default). A restart that fails is rolled back to the current release.",
    ]
    if version_tuple(target) < version_tuple(current):
        lines.extend([
            "",
            f"  Downgrade: {current} may have written storage state that {target} cannot read.",
            "  Vault does not support downgrades; restoring the binary may not be enough.",
        ])
    return lines


def warn_on_version_span(current: str, target: str) -> None:
    """Vault supports one minor version at a time; larger jumps are the user's call."""
    cur = version_tuple(current)
    tgt = version_tuple(target)
    if tgt[0] != cur[0]:
        log_warn(f"Major version change {current} -> {target}; read the upgrade guide first")
    elif tgt[1] - cur[1] > 1:
        log_warn(f"{current} -> {target} skips {tgt[1] - cur[1] - 1} minor release(s); "
                 "Vault expects one minor version at a time")


def confirm_upgrade(assume_yes: bool) -> None:
    if assume_yes:
        return
    try:
        answer = input("Proceed with the upgrade? Type yes to continue: ")
    except EOFError as exc:
        raise CLIError("Upgrade requires confirmation. Re-run with --yes for non-interactive use") from exc
    if answer != "yes":
        raise CLIError("Upgrade cancelled")


def cmd_upgrade(args: argparse.Namespace) -> int:
    require_linux()
    for command in ("install", "systemctl"):
        require_command(command)
    if args.keep < 1:
        raise CLIError("--keep must be at least 1")
    if not BIN_PATH.exists():
        raise CLIError(f"Vault is not installed at {BIN_PATH}; run {VAULT_MANAGER_CMD} install first")
    current = installed_binary_version() or read_installed_vault_version()
    if not current or current == "unknown":
        raise CLIError(f"Cannot determine the installed Vault version from {BIN_PATH}")
    target = resolve_upgrade_target(args.version)
    if target == current:
        log_success(f"Vault {current} is already installed; nothing to upgrade")
        recorded = read_installed_vault_version()
        if recorded != current:
            # doctor sends the operator here when the two disagree, so settle it instead of only reporting it
            log_info(f"Recording the installed version over {recorded}")
            record_upgrade_metadata(recorded, current)
        return 0
    if version_tuple(target) < version_tuple(current) and not args.allow_downgrade:
        raise CLIError(f"Refusing to downgrade Vault {current} to {target}; re-run with --allow-downgrade")
    print("\n".join(upgrade_plan_lines(current, target, args.keep)))
    warn_on_version_span(current, target)
    if args.dry_run:
        return 0
    confirm_upgrade(args.yes)
    client = VaultClient(args)
    arch = detect_arch()
    previous = linked_binary_path(BIN_PATH)
    if previous is None:
        log_info(f"Moving the installed binary into {BINARY_VERSION_DIR}")
        previous = adopt_versioned_binary_layout(BIN_PATH, BINARY_VERSION_DIR, "vault", current)
    tmpdir = create_install_tmpdir("vault-upgrade")
    try:
        download_vault(target, arch, tmpdir)
        staged = stage_binary(tmpdir, target)
        log_info(f"Switching {BIN_PATH} to {staged.name}")
        atomic_symlink(staged, BIN_PATH)
        try:
            log_info("Restarting Vault on the new binary")
            restart_vault_service(client)
        except (CLIError, subprocess.CalledProcessError) as exc:
            log_error(f"Vault did not come back on {target}: {exc}")
            log_warn(f"Rolling back to {previous.name}")
            atomic_symlink(previous, BIN_PATH)
            try:
                restart_vault_service(client)
            except (CLIError, subprocess.CalledProcessError) as rollback_error:
                raise CLIError(f"Upgrade to {target} failed and the rollback to {current} also failed: "
                               f"{rollback_error}") from exc
            raise CLIError(f"Upgrade to {target} failed and was rolled back to {current}") from exc
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)
    record_upgrade_metadata(current, target)
    for removed in prune_binary_versions(BINARY_VERSION_DIR, "vault", keep=args.keep, current=staged):
        log_info(f"Removed old release: {removed}")
    log_success(f"Vault upgraded: {current} -> {target}")
    print("\nVault is sealed after the restart. Next steps:")
    print(f"  1. {VAULT_MANAGER_CMD} unseal --keys-file {DEFAULT_INIT_FILE}")
    print(f"  2. {VAULT_MANAGER_CMD} doctor")
    return 0


