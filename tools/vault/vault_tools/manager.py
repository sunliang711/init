def wait_for_vault_api(client: VaultClient) -> None:
    url = client.health_url()
    log_info("Waiting for Vault HTTP API")
    for _ in range(60):
        if http_status(url, cafile=client.ca_cert) in {200, 429, 472, 473, 501, 503}:
            return
        if command_exists("systemctl") and run_root(["systemctl", "is-active", "--quiet", "vault"], check=False).returncode != 0:
            log_error("Vault service is not active")
            if command_exists("journalctl"):
                run_root(["journalctl", "-u", "vault", "-n", "80", "--no-pager"], check=False)
            raise CLIError("Vault service failed to start")
        time.sleep(2)
    if command_exists("journalctl"):
        run_root(["journalctl", "-u", "vault", "-n", "80", "--no-pager"], check=False)
    raise CLIError(f"Timed out waiting for Vault HTTP API: {url}")


